param(
  [string]$OutDir = ""
)
$ErrorActionPreference = "Stop"

# Build the package-external Updater Helper (single-file .NET Framework executable).
#
# The helper must NOT live in the package root: it is shipped as
#   <package>\tools\updater\PaperLibraryUpdater.exe
# and the app copies it to %LOCALAPPDATA%\PaperLibrary\updater\<version>\ before running it.
# This script writes the executable plus helper.json (version + sha256 metadata) there.
#
# Usage:
#   powershell -File tools\make_updater.ps1 -OutDir <package-root>
#
# The script is intentionally ASCII-only: Windows PowerShell 5.1 reads a BOM-less file as
# ANSI, so non-ASCII text here would be garbled. The C# source it compiles is ASCII-only
# for the same reason (csc without a BOM uses the ANSI code page).

$root = Split-Path -Parent $PSScriptRoot
if (-not $OutDir) { $OutDir = $root }
if (-not (Test-Path -LiteralPath $OutDir)) {
  throw "OutDir does not exist: $OutDir"
}

$source = Join-Path $root "tools\updater\PaperLibraryUpdater.cs"
if (-not (Test-Path -LiteralPath $source)) {
  throw "Missing helper source: $source"
}

$versionFile = Join-Path $root "version.json"
if (-not (Test-Path -LiteralPath $versionFile)) {
  throw "Missing version.json: $versionFile"
}
# Read the three string fields with .NET + regex instead of ConvertFrom-Json/Get-FileHash:
# those utility cmdlets are unavailable in some Windows PowerShell configurations
# (they depend on the Microsoft.PowerShell.Utility module being loadable).
$versionText = [System.IO.File]::ReadAllText($versionFile, [System.Text.Encoding]::UTF8)
function Get-VersionField([string]$text, [string]$name) {
  $match = [regex]::Match($text, '"' + [regex]::Escape($name) + '"\s*:\s*"([^"]*)"')
  if (-not $match.Success) { throw "version.json is missing the string field '$name'" }
  return $match.Groups[1].Value
}
$product = Get-VersionField $versionText "product"
$ver = Get-VersionField $versionText "version"
$tag = Get-VersionField $versionText "tag"
if ($product -ne "PaperLibrary") { throw "version.json product must be PaperLibrary (got '$product')" }
if ($ver -notmatch '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$') {
  throw "version.json version must be x.y.z (got '$ver')"
}
$parts = $ver.Split('.')
$patch = [int]$parts[2]
$expectedTag = "v" + $parts[0] + "." + $parts[1]
if ($patch -gt 0) { $expectedTag = $expectedTag + "." + $parts[2] }
if ($tag -ne $expectedTag) {
  throw "version.json tag must be $expectedTag for version $ver (got '$tag')"
}

$csc = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path -LiteralPath $csc)) {
  $csc = Join-Path $env:WINDIR "Microsoft.NET\Framework\v4.0.30319\csc.exe"
}
if (-not (Test-Path -LiteralPath $csc)) {
  throw "csc.exe (.NET Framework 4.x) not found; cannot build the updater helper"
}

$outDirPath = Join-Path $OutDir "tools\updater"
New-Item -ItemType Directory -Path $outDirPath -Force | Out-Null
$exe = Join-Path $outDirPath "PaperLibraryUpdater.exe"

$versionSource = @"
// Generated by tools/make_updater.ps1 -- do not edit or commit.
internal static class HelperInfo
{
    public const string Product = "$product";
    public const string Version = "$ver";
    public const string Tag = "$tag";
    public const int Schema = 1;
}
"@
$versionCs = Join-Path ([System.IO.Path]::GetTempPath()) ("paperlibrary-helper-version-" + [guid]::NewGuid().ToString("N") + ".cs")
try {
  [System.IO.File]::WriteAllText($versionCs, $versionSource, (New-Object System.Text.UTF8Encoding($true)))
  & $csc /nologo /target:exe /optimize+ /out:$exe /r:System.dll /r:System.Web.Extensions.dll $source $versionCs
  if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $exe)) {
    throw "helper compile failed (csc exit code $LASTEXITCODE)"
  }
} finally {
  Remove-Item $versionCs -Force -ErrorAction SilentlyContinue
}

if (Test-Path -LiteralPath (Join-Path $OutDir "PaperLibraryUpdater.exe")) {
  throw "the updater helper must not live in the package root: $OutDir"
}

$item = Get-Item -LiteralPath $exe
$sha256 = [System.Security.Cryptography.SHA256]::Create()
try {
  $stream = [System.IO.File]::OpenRead($exe)
  try { $hashBytes = $sha256.ComputeHash($stream) } finally { $stream.Close() }
} finally { $sha256.Dispose() }
$hashBuilder = New-Object System.Text.StringBuilder
foreach ($byte in $hashBytes) { [void]$hashBuilder.Append($byte.ToString("x2")) }
$hash = $hashBuilder.ToString()
$builtAt = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
$metaJson = @"
{
  "schema": 1,
  "product": "$product",
  "version": "$ver",
  "tag": "$tag",
  "exe": "PaperLibraryUpdater.exe",
  "bytes": $($item.Length),
  "sha256": "$hash",
  "builtAt": "$builtAt",
  "source": "tools/updater/PaperLibraryUpdater.cs",
  "runtime": ".NET Framework 4.x csc"
}
"@
[System.IO.File]::WriteAllText((Join-Path $outDirPath "helper.json"), $metaJson, (New-Object System.Text.UTF8Encoding($false)))

Write-Output ("updater helper built: " + $exe)
Write-Output ("updater helper version: " + $ver + " (" + $tag + ")")
Write-Output ("updater helper sha256: " + $hash)
Write-Output ("updater helper bytes: " + $item.Length)

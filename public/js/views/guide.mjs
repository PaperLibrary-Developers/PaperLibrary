  /* ---------------- 排版小工具 ---------------- */

  function sec (meta, ...body) {
    return h('section.doc-sec', { id: meta.id },
      h('h2.doc-h2',
        h('span.doc-num', meta.num),
        h('span', meta.title)
      ),
      meta.lead ? h('p.doc-lead', meta.lead) : null,
      ...body
    )
  }

  function sub (title, ...body) {
    return h('div.doc-sub', h('h3', title), ...body)
  }

  function p (text) { return h('p', text) }
  function ul (items) { return h('ul', items.map(t => h('li', t))) }
  function ol (items) { return h('ol', items.map(t => h('li', t))) }

  function table (head, rows) {
    // 外壳负责横向滚动：窄屏上表格比页面宽时只滚表格，不把整页撑出横向滚动条
    return h('div.doc-table-wrap',
      h('table.doc-table',
        h('thead', h('tr', head.map(c => h('th', c)))),
        h('tbody', rows.map(row => h('tr',
          row.map((cell, i) => h('td' + (i === 0 ? '.doc-td-key' : ''), cell))
        )))
      )
    )
  }

  /** 代码块 + 一键复制（命令都写在这里，别让新手从截图里手敲） */
  function code (text, caption) {
    const btn = h('button.doc-copy', {
      type: 'button',
      title: '复制这段命令',
      onclick: async () => {
        try {
          await copyText(text)
          toast('已复制')
        } catch {
          toast('复制失败，请手动选中', 'warn')
        }
      }
    }, '复制')
    return h('div.doc-code',
      caption ? h('div.doc-code-cap', caption) : null,
      h('pre', h('code', text)),
      btn
    )
  }

  /** 提示块：tip = 小技巧，warn = 容易踩的坑，danger = 会丢数据 */
  function call (kind, title, ...body) {
    const icon = kind === 'danger' ? '⛔' : kind === 'warn' ? '⚠️' : '💡'
    return h('div.doc-call.doc-call--' + kind,
      h('div.doc-call-title', icon + ' ' + title),
      h('div.doc-call-body', ...body)
    )
  }

